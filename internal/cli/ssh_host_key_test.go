package cli

import (
	"bytes"
	"crypto/ecdh"
	"crypto/rand"
	"encoding/base64"
	"strings"
	"testing"
)

// sshTestPublicLine renders a declared type and wire blob as a key line.
func sshTestPublicLine(keyType string, blob []byte) string {
	return keyType + " " + base64.StdEncoding.EncodeToString(blob)
}

// sshTestEd25519Blob builds an ssh-ed25519 blob.
func sshTestEd25519Blob() []byte {
	var writer sshWireWriter
	writer.stringBytes([]byte("ssh-ed25519"))
	writer.stringBytes(bytes.Repeat([]byte{9}, 32))
	return writer.bytes()
}

// sshTestECDSABlob builds an ECDSA blob for the given type and curve.
func sshTestECDSABlob(t *testing.T, keyType string, curve ecdh.Curve, curveName string, securityKey bool) []byte {
	t.Helper()
	privateKey, err := curve.GenerateKey(rand.Reader)
	if err != nil {
		t.Fatalf("generate ecdsa: %v", err)
	}
	point := privateKey.PublicKey().Bytes()
	var writer sshWireWriter
	writer.stringBytes([]byte(keyType))
	writer.stringBytes([]byte(curveName))
	writer.stringBytes(point)
	if securityKey {
		writer.stringBytes([]byte("ssh:"))
	}
	return writer.bytes()
}

// sshTestRSABlob builds a structurally valid RSA blob.
func sshTestRSABlob() []byte {
	exponent := []byte{0x01, 0x00, 0x01}
	modulus := bytes.Repeat([]byte{0x7f}, 256)
	var writer sshWireWriter
	writer.stringBytes([]byte("ssh-rsa"))
	writer.stringBytes(exponent)
	writer.stringBytes(modulus)
	return writer.bytes()
}

// TestParseSSHHostKeyValid covers every supported host key family.
func TestParseSSHHostKeyValid(t *testing.T) {
	cases := []struct {
		name  string
		value string
	}{
		{name: "ed25519", value: sshTestPublicLine("ssh-ed25519", sshTestEd25519Blob())},
		{name: "ed25519 with comment", value: sshTestPublicLine("ssh-ed25519", sshTestEd25519Blob()) + " user@host"},
		{name: "ed25519 multiword comment", value: sshTestPublicLine("ssh-ed25519", sshTestEd25519Blob()) + " user@host generated by test key"},
		{name: "tab separators", value: "ssh-ed25519\t" + base64.StdEncoding.EncodeToString(sshTestEd25519Blob()) + "\tuser@host"},
		{name: "tab separators multiword", value: "ssh-ed25519\t" + base64.StdEncoding.EncodeToString(sshTestEd25519Blob()) + "\tuser@host\twith words"},
		{name: "rsa", value: sshTestPublicLine("ssh-rsa", sshTestRSABlob())},
		{name: "ecdsa p256", value: sshTestPublicLine("ecdsa-sha2-nistp256", sshTestECDSABlob(t, "ecdsa-sha2-nistp256", ecdh.P256(), "nistp256", false))},
		{name: "ecdsa p384", value: sshTestPublicLine("ecdsa-sha2-nistp384", sshTestECDSABlob(t, "ecdsa-sha2-nistp384", ecdh.P384(), "nistp384", false))},
		{name: "ecdsa p521", value: sshTestPublicLine("ecdsa-sha2-nistp521", sshTestECDSABlob(t, "ecdsa-sha2-nistp521", ecdh.P521(), "nistp521", false))},
		{name: "sk ed25519", value: sshTestPublicLine("sk-ssh-ed25519@openssh.com", func() []byte {
			var writer sshWireWriter
			writer.stringBytes([]byte("sk-ssh-ed25519@openssh.com"))
			writer.stringBytes(bytes.Repeat([]byte{4}, 32))
			writer.stringBytes([]byte("ssh:"))
			return writer.bytes()
		}())},
		{name: "sk ecdsa", value: sshTestPublicLine("sk-ecdsa-sha2-nistp256@openssh.com", sshTestECDSABlob(t, "sk-ecdsa-sha2-nistp256@openssh.com", ecdh.P256(), "nistp256", true))},
		{name: "webauthn sk ecdsa", value: sshTestPublicLine("webauthn-sk-ecdsa-sha2-nistp256@openssh.com", sshTestECDSABlob(t, "webauthn-sk-ecdsa-sha2-nistp256@openssh.com", ecdh.P256(), "nistp256", true))},
	}
	for _, testCase := range cases {
		t.Run(testCase.name, func(t *testing.T) {
			key, err := parseSSHHostKey(testCase.value)
			if err != nil {
				t.Fatalf("parse: %v", err)
			}
			if key.Type == "" || len(key.Blob) == 0 {
				t.Fatalf("key = %+v, want type and blob", key)
			}
			line := key.knownHostsLine(sshTestSandboxID)
			fields := strings.Fields(line)
			if len(fields) != 3 || fields[0] != sshTestSandboxID || fields[1] != key.Type {
				t.Fatalf("known_hosts line = %q", line)
			}
		})
	}
}

// sshTestRSAHostKeyExponentOne builds an ssh-rsa key with e = 1 and an odd
// modulus. It is structurally invalid for public-key verification.
func sshTestRSAHostKeyExponentOne() string {
	var writer sshWireWriter
	writer.stringBytes([]byte("ssh-rsa"))
	writer.stringBytes([]byte{0x01})
	writer.stringBytes(bytes.Repeat([]byte{0x7f}, 256))
	return sshTestPublicLine("ssh-rsa", writer.bytes())
}

// TestParseSSHHostKeyInvalid rejects structural violations, unsupported types
// and any blob whose inner type does not match.
func TestParseSSHHostKeyInvalid(t *testing.T) {
	ed25519Blob := sshTestEd25519Blob()
	shortEd25519 := func() []byte {
		var writer sshWireWriter
		writer.stringBytes([]byte("ssh-ed25519"))
		writer.stringBytes(bytes.Repeat([]byte{1}, 31))
		return writer.bytes()
	}()
	trailing := append(bytes.Clone(ed25519Blob), 0)
	wrongInner := func() []byte {
		var writer sshWireWriter
		writer.stringBytes([]byte("ssh-rsa"))
		writer.stringBytes([]byte{1})
		return writer.bytes()
	}()
	negativeRSA := func() []byte {
		var writer sshWireWriter
		writer.stringBytes([]byte("ssh-rsa"))
		writer.stringBytes([]byte{0x80, 0x01})
		writer.stringBytes(bytes.Repeat([]byte{0x7f}, 256))
		return writer.bytes()
	}()
	smallRSA := func() []byte {
		var writer sshWireWriter
		writer.stringBytes([]byte("ssh-rsa"))
		writer.stringBytes([]byte{0x01, 0x00, 0x01})
		writer.stringBytes([]byte{0x03})
		return writer.bytes()
	}()
	evenRSA := func() []byte {
		var writer sshWireWriter
		writer.stringBytes([]byte("ssh-rsa"))
		writer.stringBytes([]byte{0x01, 0x00, 0x01})
		writer.stringBytes(bytes.Repeat([]byte{0x7e}, 256))
		return writer.bytes()
	}()
	evenExponent := func() []byte {
		var writer sshWireWriter
		writer.stringBytes([]byte("ssh-rsa"))
		writer.stringBytes([]byte{0x01, 0x00, 0x02})
		writer.stringBytes(bytes.Repeat([]byte{0x7f}, 256))
		return writer.bytes()
	}()
	emptySKApplication := func() []byte {
		var writer sshWireWriter
		writer.stringBytes([]byte("sk-ssh-ed25519@openssh.com"))
		writer.stringBytes(bytes.Repeat([]byte{4}, 32))
		writer.stringBytes(nil)
		return writer.bytes()
	}()
	badCurveName := func() []byte {
		var writer sshWireWriter
		writer.stringBytes([]byte("ecdsa-sha2-nistp256"))
		writer.stringBytes([]byte("nistp384"))
		writer.stringBytes(bytes.Repeat([]byte{0x04}, 65))
		return writer.bytes()
	}()
	offCurve := sshTestECDSABlob(t, "ecdsa-sha2-nistp256", ecdh.P256(), "nistp256", false)
	offCurve[len(offCurve)-1] ^= 0xff

	cases := []struct {
		name  string
		value string
	}{
		{name: "empty", value: ""},
		{name: "one field", value: "ssh-ed25519"},
		{name: "leading space only", value: "   "},
		{name: "embedded newline", value: sshTestPublicLine("ssh-ed25519", ed25519Blob) + "\nssh-ed25519 AAAA"},
		{name: "trailing newline", value: sshTestPublicLine("ssh-ed25519", ed25519Blob) + "\n"},
		{name: "carriage return", value: sshTestPublicLine("ssh-ed25519", ed25519Blob) + "\r"},
		{name: "NUL byte", value: sshTestPublicLine("ssh-ed25519", ed25519Blob) + "\x00"},
		{name: "vertical tab", value: "ssh-ed25519\x0b" + base64.StdEncoding.EncodeToString(ed25519Blob)},
		{name: "unsupported dss", value: "ssh-dss AAAAB3NzaC1kc3M="},
		{name: "certificate", value: "ssh-ed25519-cert-v01@openssh.com " + base64.StdEncoding.EncodeToString(ed25519Blob)},
		{name: "bad base64", value: "ssh-ed25519 !!!"},
		{name: "short ed25519", value: sshTestPublicLine("ssh-ed25519", shortEd25519)},
		{name: "trailing blob byte", value: sshTestPublicLine("ssh-ed25519", trailing)},
		{name: "inner type mismatch", value: sshTestPublicLine("ssh-ed25519", wrongInner)},
		{name: "negative rsa exponent", value: sshTestPublicLine("ssh-rsa", negativeRSA)},
		{name: "rsa exponent one", value: sshTestRSAHostKeyExponentOne()},
		{name: "rsa modulus not above exponent", value: sshTestPublicLine("ssh-rsa", smallRSA)},
		{name: "even rsa modulus", value: sshTestPublicLine("ssh-rsa", evenRSA)},
		{name: "even rsa exponent", value: sshTestPublicLine("ssh-rsa", evenExponent)},
		{name: "empty sk application", value: sshTestPublicLine("sk-ssh-ed25519@openssh.com", emptySKApplication)},
		{name: "ecdsa curve mismatch", value: sshTestPublicLine("ecdsa-sha2-nistp256", badCurveName)},
		{name: "ecdsa off curve", value: sshTestPublicLine("ecdsa-sha2-nistp256", offCurve)},
	}
	for _, testCase := range cases {
		t.Run(testCase.name, func(t *testing.T) {
			if _, err := parseSSHHostKey(testCase.value); err == nil {
				t.Fatalf("parse %q succeeded, want error", testCase.value)
			}
		})
	}
}
