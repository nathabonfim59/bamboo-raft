// sshString returns a pointer to value.
func sshTestString(value string) *string { return &value }

// TestInstallSSHKeyRequestAndTarget pins the request and the IPv4 target.
func TestInstallSSHKeyRequestAndTarget(t *testing.T) {
	hostKey := sshTestHostKey(1)
	var body map[string]any
	handler := func(w http.ResponseWriter, r *http.Request) {
		if r.Method != http.MethodPost {
			t.Errorf("method = %s, want POST", r.Method)
		}
		if want := "/api/v1/sandboxes/" + sshTestSandboxID + "/sshkey"; r.URL.Path != want {
			t.Errorf("path = %s, want %s", r.URL.Path, want)
		}
		if got := r.Header.Get("Authorization"); got != "Bearer test-key" {
			t.Errorf("authorization = %q", got)
		}
		if got := r.Header.Get("Content-Type"); got != "application/json" {
			t.Errorf("content type = %q", got)
		}
		raw, err := io.ReadAll(r.Body)
		if err != nil {
			t.Errorf("read body: %v", err)
		}
		if err := json.Unmarshal(raw, &body); err != nil {
			t.Errorf("decode body: %v", err)
		}
		cliTestWriteJSON(t, w, http.StatusOK, sshTestResponse(sshTestString("203.0.113.10"), nil, hostKey))
	}
	target, err := sshTestInstall(t, handler, sshTestSandboxID, sshTestPublicKey)
	if err != nil {
		t.Fatalf("install ssh key: %v", err)
	}
	if target.Host != "203.0.113.10" || target.Port != 22 || target.User != sshTestUser {
		t.Fatalf("target = %+v, want 203.0.113.10:22 user", target)
	}
	if target.HostKey.Type != "ssh-ed25519" || len(target.HostKey.Blob) == 0 {
		t.Fatalf("host key = %+v, want validated ed25519", target.HostKey)
	}
	if len(body) != 1 || body["key"] != sshTestPublicKey {
		t.Fatalf("body = %v, want only key=%q", body, sshTestPublicKey)
	}
}

