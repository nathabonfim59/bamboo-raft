// TestInstallSSHKeyTargets covers nullable machineIp/sshEndpoint combinations.
func TestInstallSSHKeyTargets(t *testing.T) {
	hostKey := sshTestHostKey(2)
	cases := []struct {
		name      string
		machineIP *string
		endpoint  *string
		host      string
		port      int
	}{
		{name: "machine ip", machineIP: sshTestString("203.0.113.10"), host: "203.0.113.10", port: 22},
		{name: "endpoint ipv4", endpoint: sshTestString("203.0.113.10:22001"), host: "203.0.113.10", port: 22001},
		{name: "endpoint ipv6", endpoint: sshTestString("[2001:db8::1]:2222"), host: "2001:db8::1", port: 2222},
		{name: "empty endpoint falls back", machineIP: sshTestString("198.51.100.7"), endpoint: sshTestString(""), host: "198.51.100.7", port: 22},
		{name: "bracketed machine ip", machineIP: sshTestString("[2001:db8::5]"), host: "2001:db8::5", port: 22},
		{name: "hostname endpoint", endpoint: sshTestString("ssh.example.test:2200"), host: "ssh.example.test", port: 2200},
		{name: "endpoint with null machine ip", endpoint: sshTestString("203.0.113.10:22001"), host: "203.0.113.10", port: 22001},
	}
	for _, testCase := range cases {
		t.Run(testCase.name, func(t *testing.T) {
			handler := func(w http.ResponseWriter, _ *http.Request) {
				cliTestWriteJSON(t, w, http.StatusOK, sshTestResponse(testCase.machineIP, testCase.endpoint, hostKey))
			}
			target, err := sshTestInstall(t, handler, sshTestSandboxID, sshTestPublicKey)
			if err != nil {
				t.Fatalf("install ssh key: %v", err)
			}
			if target.Host != testCase.host || target.Port != testCase.port {
				t.Fatalf("target = %s:%d, want %s:%d", target.Host, target.Port, testCase.host, testCase.port)
			}
		})
	}
}

// TestInstallSSHKeyInvalidResponses rejects malformed targets and envelopes.
func TestInstallSSHKeyInvalidResponses(t *testing.T) {
	validHostKey := sshTestHostKey(3)
	invalid := func(mutate func(map[string]any)) map[string]any {
		response := sshTestResponse(sshTestString("203.0.113.10"), nil, validHostKey)
		mutate(response)
		return response
	}
	cases := []struct {
		name string
		body any
	}{
		{name: "no address", body: sshTestResponse(nil, nil, validHostKey)},
		{name: "ok false", body: invalid(func(m map[string]any) { m["ok"] = false })},
		{name: "wrong type", body: invalid(func(m map[string]any) { m["type"] = "sandbox.info" })},
		{name: "empty user", body: invalid(func(m map[string]any) { m["sshUser"] = "" })},
		{name: "leading dash user", body: invalid(func(m map[string]any) { m["sshUser"] = "-user" })},
		{name: "space user", body: invalid(func(m map[string]any) { m["sshUser"] = "us er" })},
		{name: "at user", body: invalid(func(m map[string]any) { m["sshUser"] = "user@host" })},
		{name: "colon user", body: invalid(func(m map[string]any) { m["sshUser"] = "user:host" })},
		{name: "empty endpoint and empty ip", body: sshTestResponse(sshTestString(""), sshTestString(""), validHostKey)},
		{name: "endpoint no port", body: sshTestResponse(nil, sshTestString("203.0.113.10"), validHostKey)},
		{name: "endpoint port zero", body: sshTestResponse(nil, sshTestString("203.0.113.10:0"), validHostKey)},
		{name: "endpoint port too large", body: sshTestResponse(nil, sshTestString("203.0.113.10:65536"), validHostKey)},
		{name: "endpoint port letters", body: sshTestResponse(nil, sshTestString("203.0.113.10:22a"), validHostKey)},
		{name: "endpoint port plus", body: sshTestResponse(nil, sshTestString("203.0.113.10:+22"), validHostKey)},
		{name: "endpoint bare ipv6", body: sshTestResponse(nil, sshTestString("2001:db8::1:22"), validHostKey)},
		{name: "leading dash host", body: sshTestResponse(sshTestString("-host"), nil, validHostKey)},
		{name: "space host", body: sshTestResponse(sshTestString("host name"), nil, validHostKey)},
		{name: "slash host", body: sshTestResponse(sshTestString("host/path"), nil, validHostKey)},
		{name: "colon machine ip", body: sshTestResponse(sshTestString("host:22"), nil, validHostKey)},
		{name: "missing host key", body: invalid(func(m map[string]any) { m["hostKey"] = "" })},
		{name: "bad host key base64", body: invalid(func(m map[string]any) { m["hostKey"] = "ssh-ed25519 !!!" })},
		{name: "short host key", body: invalid(func(m map[string]any) { m["hostKey"] = "ssh-ed25519 QUFBQQ==" })},
		{name: "unsupported host key", body: invalid(func(m map[string]any) { m["hostKey"] = "ssh-dss AAAAB3NzaC1kc3M=" })},
		{name: "newline host key", body: invalid(func(m map[string]any) { m["hostKey"] = validHostKey + "\nssh-ed25519 AAAA" })},
	}
	for _, testCase := range cases {
		t.Run(testCase.name, func(t *testing.T) {
			handler := func(w http.ResponseWriter, _ *http.Request) {
				cliTestWriteJSON(t, w, http.StatusOK, testCase.body)
			}
			_, err := sshTestInstall(t, handler, sshTestSandboxID, sshTestPublicKey)
			if err == nil {
				t.Fatal("install ssh key succeeded, want invalid_response")
			}
			cliErr, ok := errors.AsType[*CLIError](err)
			if !ok || cliErr.Code != "invalid_response" {
				t.Fatalf("error = %v, want CLIError invalid_response", err)
			}
		})
	}
}

// TestInstallSSHKeyStatuses pins exact-200 handling and API error decoding.
func TestInstallSSHKeyStatuses(t *testing.T) {
	hostKey := sshTestHostKey(4)
	validBody := sshTestResponse(sshTestString("203.0.113.10"), nil, hostKey)
	t.Run("503 envelope", func(t *testing.T) {
		handler := func(w http.ResponseWriter, _ *http.Request) {
			cliTestWriteJSON(t, w, http.StatusServiceUnavailable,
				cliTestErrorEnvelope(http.StatusServiceUnavailable, "ssh_host_key_unavailable", "host key is not ready"))
		}
		_, err := sshTestInstall(t, handler, sshTestSandboxID, sshTestPublicKey)
		apiErr, ok := errors.AsType[*APIError](err)
		if !ok || apiErr.Status != http.StatusServiceUnavailable || apiErr.Code != "ssh_host_key_unavailable" {
			t.Fatalf("error = %#v, want APIError 503 ssh_host_key_unavailable", err)
		}
	})
	for _, status := range []int{http.StatusCreated, http.StatusAccepted} {
		t.Run(http.StatusText(status), func(t *testing.T) {
			handler := func(w http.ResponseWriter, _ *http.Request) {
				cliTestWriteJSON(t, w, status, validBody)
			}
			_, err := sshTestInstall(t, handler, sshTestSandboxID, sshTestPublicKey)
			if err == nil {
				t.Fatalf("status %d succeeded, want an error", status)
			}
		})
	}
	t.Run("204 no content", func(t *testing.T) {
		handler := func(w http.ResponseWriter, _ *http.Request) {
			w.WriteHeader(http.StatusNoContent)
		}
		_, err := sshTestInstall(t, handler, sshTestSandboxID, sshTestPublicKey)
		if err == nil {
			t.Fatal("status 204 succeeded, want an error")
		}
	})
	t.Run("200 ok false", func(t *testing.T) {
		body := sshTestResponse(sshTestString("203.0.113.10"), nil, hostKey)
		body["ok"] = false
		handler := func(w http.ResponseWriter, _ *http.Request) {
			cliTestWriteJSON(t, w, http.StatusOK, body)
		}
		_, err := sshTestInstall(t, handler, sshTestSandboxID, sshTestPublicKey)
		cliErr, ok := errors.AsType[*CLIError](err)
		if !ok || cliErr.Code != "invalid_response" {
			t.Fatalf("error = %v, want invalid_response", err)
		}
	})
	t.Run("wrong media type", func(t *testing.T) {
		handler := func(w http.ResponseWriter, _ *http.Request) {
			w.Header().Set("Content-Type", "text/plain")
			w.WriteHeader(http.StatusOK)
			_, _ = w.Write([]byte("ok"))
		}
		_, err := sshTestInstall(t, handler, sshTestSandboxID, sshTestPublicKey)
		cliErr, ok := errors.AsType[*CLIError](err)
		if !ok || cliErr.Code != "invalid_response" {
			t.Fatalf("error = %v, want invalid_response", err)
		}
	})
	t.Run("malformed json", func(t *testing.T) {
		handler := func(w http.ResponseWriter, _ *http.Request) {
			w.Header().Set("Content-Type", "application/json")
			w.WriteHeader(http.StatusOK)
			_, _ = io.WriteString(w, "{")
		}
		_, err := sshTestInstall(t, handler, sshTestSandboxID, sshTestPublicKey)
		cliErr, ok := errors.AsType[*CLIError](err)
		if !ok || cliErr.Code != "invalid_response" {
			t.Fatalf("error = %v, want invalid_response", err)
		}
	})
	t.Run("public key with newline never sent", func(t *testing.T) {
		called := false
		handler := func(http.ResponseWriter, *http.Request) { called = true }
		_, err := sshTestInstall(t, handler, sshTestSandboxID, "ssh-ed25519 AAAA\nbad")
		if err == nil || called {
			t.Fatalf("error = %v called = %v, want local rejection", err, called)
		}
	})
	t.Run("cancel propagates", func(t *testing.T) {
		server := newSSHTestServer(t, func(w http.ResponseWriter, _ *http.Request) {
			cliTestWriteJSON(t, w, http.StatusOK, validBody)
		})
		client, err := NewClient(server.URL, "test-key", server.Client())
		if err != nil {
			t.Fatalf("new client: %v", err)
		}
		ctx, cancel := context.WithCancel(t.Context())
		cancel()
		_, err = installSSHKey(ctx, client, sshTestSandboxID, sshTestPublicKey)
		if !errors.Is(err, context.Canceled) {
			t.Fatalf("error = %v, want context.Canceled", err)
		}
	})
}

// TestInstallSSHKeyRejectsInvalidSandboxID refuses an id that could break the
// path or the known_hosts alias before any request.
func TestInstallSSHKeyRejectsInvalidSandboxID(t *testing.T) {
	called := false
	handler := func(http.ResponseWriter, *http.Request) { called = true }
	_, err := sshTestInstall(t, handler, "not-a-sandbox", sshTestPublicKey)
	if err == nil || called {
		t.Fatalf("error = %v called = %v, want local rejection", err, called)
	}
	cliErr, ok := errors.AsType[*CLIError](err)
	if !ok || cliErr.Code != "invalid_response" {
		t.Fatalf("error = %v, want invalid_response", err)
	}
	if strings.Contains(err.Error(), sshTestPublicKey) {
		t.Fatal("error contains key material")
	}
}
