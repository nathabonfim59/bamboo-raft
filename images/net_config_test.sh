#!/usr/bin/env bash
# Fast regressions for the TAP-mode static network generator
# (images/mkosi.extra/usr/local/sbin/bbraft-network-config).
#
# The generator turns the node's strict kernel ip= parameter into
# /run/systemd/network/10-bbraft-static.network. These checks run the real
# script against injected command lines and output directories; the real boot
# is covered by the KVM acceptance run. The strict parser is the contract, so a
# regression fails here first.
set -euo pipefail
export LC_ALL=C

script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)
generator="$script_dir/mkosi.extra/usr/local/sbin/bbraft-network-config"
unit_name=10-bbraft-static.network
service=bbraft-network-config.service

tmp=$(mktemp -d "${TMPDIR:-/tmp}/bbraft-net-config.XXXXXX")
trap 'rm -rf "$tmp"' EXIT

failures=0
pass() { printf 'PASS %s\n' "$*"; }
fail() {
	printf 'FAIL %s\n' "$*" >&2
	failures=$((failures + 1))
}

# run <cmdline> <network-dir> runs the real generator with test-only overrides.
run() {
	printf '%s\n' "$1" >"$tmp/cmdline"
	mkdir -p "$2"
	BBRAFT_CMDLINE_FILE="$tmp/cmdline" BBRAFT_NETWORK_DIR="$2" \
		"$generator" 2>"$tmp/stderr"
}

assert_unit_absent() {
	if [[ -e "$1/$unit_name" ]]; then
		fail "$2: $unit_name was written for a non-TAP command line"
	else
		pass "$2: no static unit"
	fi
	if [[ -s "$tmp/stderr" ]]; then
		fail "$2: unexpected stderr: $(cat "$tmp/stderr")"
	fi
}

assert_fail_closed() {
	local what=$1 unit="$2/$unit_name" bad=0
	if [[ ! -f $unit ]]; then
		fail "$what: no fail-closed unit written"
		return
	fi
	grep -qx 'DHCP=no' "$unit" || {
		fail "$what: fail-closed unit enables DHCP"
		bad=1
	}
	grep -qx 'Name=en\* eth\*' "$unit" || {
		fail "$what: fail-closed unit does not match the guest NIC, so 20-bbraft.network DHCP could apply"
		bad=1
	}
	for key in Address Gateway DNS; do
		if grep -q "^$key=" "$unit"; then
			fail "$what: fail-closed unit configures $key"
			bad=1
		fi
	done
	grep -q 'refusing DHCP/RA fallback' "$tmp/stderr" || {
		fail "$what: no fail-closed diagnostic on stderr"
		bad=1
	}
	if [ "$bad" -eq 0 ]; then
		pass "$what: fail-closed unit disables address, DHCP and RA"
	fi
}

assert_static() {
	local dir=$1 what=$2 address=$3 gateway=$4
	shift 4
	local unit="$dir/$unit_name" bad=0
	if [[ ! -f $unit ]]; then
		fail "$what: no static unit"
		return
	fi
	grep -qx "Address=$address" "$unit" || {
		fail "$what: wrong Address"
		bad=1
	}
	grep -qx "Gateway=$gateway" "$unit" || {
		fail "$what: wrong Gateway"
		bad=1
	}
	grep -qx 'DHCP=no' "$unit" || {
		fail "$what: DHCP is not disabled"
		bad=1
	}
	grep -qx 'Name=en\* eth\*' "$unit" || {
		fail "$what: unit does not match the guest NIC"
		bad=1
	}
	local want
	for want in "$@"; do
		grep -qx "DNS=$want" "$unit" || {
			fail "$what: missing DNS=$want"
			bad=1
		}
	done
	if [[ $# -eq 0 ]] && grep -q '^DNS=' "$unit"; then
		fail "$what: unexpected DNS lines"
		bad=1
	fi
	if [ "$bad" -eq 0 ]; then
		pass "$what: static unit is exact"
	fi
}

# 1. QEMU user-mode networking (and any DHCP command line) leaves the image's
# 20-bbraft.network DHCP configuration untouched.
mkdir -p "$tmp/user/dhcp"
run 'root=/dev/vda rw console=ttyS0,115200n8 systemd.hostname=box' "$tmp/user/dhcp"
assert_unit_absent "$tmp/user/dhcp" "no ip="
mkdir -p "$tmp/user/explicit"
run 'root=/dev/vda rw ip=dhcp' "$tmp/user/explicit"
assert_unit_absent "$tmp/user/explicit" "ip=dhcp"
mkdir -p "$tmp/user/linklocal"
run 'root=/dev/vda ip=link-local' "$tmp/user/linklocal"
assert_unit_absent "$tmp/user/linklocal" "ip=link-local"

# 2. The node's exact form produces the static unit, byte for byte.
dir="$tmp/valid2"
run 'root=/dev/vda rw ip=10.42.0.2::10.42.0.1:255.255.0.0:::off:1.1.1.1:9.9.9.9' "$dir"
unit="$dir/$unit_name"
if [[ -f $unit ]]; then
	pass "valid ip= writes $unit_name"
else
	fail "valid ip= did not write $unit_name"
fi
want="$tmp/want-valid2"
cat >"$want" <<'EOF'
# Generated by bbraft-network-config from the kernel ip= parameter at boot.
# Do not edit: this file lives in /run and is regenerated on every boot.
[Match]
Name=en* eth*
Type=ether

[Network]
DHCP=no
IPv6AcceptRA=no
LinkLocalAddressing=no
Address=10.42.0.2/16
Gateway=10.42.0.1
DNS=1.1.1.1
DNS=9.9.9.9
EOF
if [[ -f $unit ]] && cmp -s "$want" "$unit"; then
	pass "static unit content is exact"
else
	fail "static unit content differs from the expected contract"
	diff -u "$want" "$unit" >&2 || true
fi
if [[ -f $unit && $(stat -c %a "$unit") == 644 ]]; then
	pass "static unit mode is 0644"
else
	fail "static unit mode is not 0644"
fi
shopt -s nullglob
leftovers=("$dir/.$unit_name.tmp."*)
shopt -u nullglob
if [[ ${#leftovers[@]} -gt 0 ]]; then
	fail "generator left temporary files behind: ${leftovers[*]}"
else
	pass "no temporary files left behind"
fi
if [[ "$(basename "$unit")" < 20-bbraft.network ]]; then
	pass "static unit sorts before the image DHCP unit"
else
	fail "static unit does not sort before 20-bbraft.network"
fi

# 3. One resolver, no resolver, /30 and /8 masks keep the same contract.
dir="$tmp/valid1"
run 'ip=10.42.0.9::10.42.0.1:255.255.0.0:::off:8.8.8.8' "$dir"
assert_static "$dir" "one resolver" "10.42.0.9/16" "10.42.0.1" 8.8.8.8
dir="$tmp/valid0"
run 'ip=10.42.0.9::10.42.0.1:255.255.0.0:::off' "$dir"
assert_static "$dir" "no resolver" "10.42.0.9/16" "10.42.0.1"
dir="$tmp/valid-30"
run 'ip=10.42.0.1::10.42.0.2:255.255.255.252:::off:1.1.1.1' "$dir"
assert_static "$dir" "/30 boundary" "10.42.0.1/30" "10.42.0.2" 1.1.1.1
dir="$tmp/valid-8"
run 'ip=10.1.2.3::10.9.9.9:255.0.0.0:::off:9.9.9.9' "$dir"
assert_static "$dir" "/8 boundary" "10.1.2.3/8" "10.9.9.9" 9.9.9.9

# 4. Malformed input never guesses: a matching unit disables DHCP, RA and
# link-local addressing, so networkd applies no address at all.
malformed=(
	'multiple|ip=10.42.0.2::10.42.0.1:255.255.0.0:::off ip=10.42.0.3::10.42.0.1:255.255.0.0:::off'
	'empty|ip='
	'trailing-field|ip=10.42.0.2::10.42.0.1:255.255.0.0:::off:'
	'too-few-fields|ip=10.42.0.2::10.42.0.1:255.255.0.0::off'
	'too-many-fields|ip=10.42.0.2::10.42.0.1:255.255.0.0:::off:1.1.1.1:9.9.9.9:8.8.8.8'
	'server-set|ip=10.42.0.2:10.42.0.1:10.42.0.1:255.255.0.0:::off'
	'hostname-set|ip=10.42.0.2::10.42.0.1:255.255.0.0:box::off'
	'device-set|ip=10.42.0.2::10.42.0.1:255.255.0.0::eth0:off'
	'autoconf-dhcp|ip=10.42.0.2::10.42.0.1:255.255.0.0:::dhcp'
	'client-999|ip=10.42.0.999::10.42.0.1:255.255.0.0:::off'
	'client-leading-zero|ip=10.42.00.2::10.42.0.1:255.255.0.0:::off'
	'client-ipv6|ip=fd00::2::10.42.0.1:255.255.0.0:::off'
	'client-equals-gateway|ip=10.42.0.2::10.42.0.2:255.255.0.0:::off'
	'client-loopback|ip=127.0.0.1::10.42.0.1:255.255.0.0:::off'
	'client-unspecified|ip=0.0.0.0::10.42.0.1:255.255.0.0:::off'
	'client-this-network|ip=0.1.2.3::0.1.0.1:255.255.0.0:::off'
	'client-reserved-240|ip=240.0.0.2::240.0.0.1:255.255.0.0:::off'
	'client-multicast|ip=224.0.0.1::10.42.0.1:255.255.0.0:::off'
	'client-reserved|ip=255.255.255.255::10.42.0.1:255.255.0.0:::off'
	'gateway-outside|ip=10.42.0.2::10.43.0.1:255.255.0.0:::off'
	'gateway-loopback|ip=10.42.0.2::127.0.0.1:255.255.0.0:::off'
	'gateway-unspecified|ip=10.42.0.2::0.0.0.0:255.255.0.0:::off'
	'gateway-multicast|ip=10.42.0.2::239.1.1.1:255.255.0.0:::off'
	'client-network-address|ip=10.42.0.0::10.42.0.1:255.255.0.0:::off'
	'client-broadcast|ip=10.42.255.255::10.42.0.1:255.255.0.0:::off'
	'gateway-network-address|ip=10.42.0.2::10.42.0.0:255.255.0.0:::off'
	'non-contiguous-mask|ip=10.42.0.2::10.42.0.1:255.0.255.0:::off'
	'prefix-7|ip=10.42.0.2::10.42.0.1:254.0.0.0:::off'
	'prefix-31|ip=10.42.0.2::10.42.0.1:255.255.255.254:::off'
	'dns-loopback|ip=10.42.0.2::10.42.0.1:255.255.0.0:::off:127.0.0.1'
	'dns-in-subnet|ip=10.42.0.2::10.42.0.1:255.255.0.0:::off:10.42.0.53'
	'dns-multicast|ip=10.42.0.2::10.42.0.1:255.255.0.0:::off:224.0.0.1'
	'dns-zero|ip=10.42.0.2::10.42.0.1:255.255.0.0:::off:0.0.0.0'
	'dns-invalid|ip=10.42.0.2::10.42.0.1:255.255.0.0:::off:nameserver'
	'dns-reserved|ip=10.42.0.2::10.42.0.1:255.255.0.0:::off:240.0.0.1'
	'dns-this-network|ip=10.42.0.2::10.42.0.1:255.255.0.0:::off:0.1.2.3'
	'dns-reserved-240|ip=10.42.0.2::10.42.0.1:255.255.0.0:::off:240.0.0.2'
)
for entry in "${malformed[@]}"; do
	name=${entry%%|*}
	cmdline=${entry#*|}
	dir="$tmp/bad/$name"
	if ! run "$cmdline" "$dir"; then
		fail "$name: generator exited non-zero; fail-closed must finish the boot"
		continue
	fi
	assert_fail_closed "$name" "$dir"
done

# 5. A later good run replaces a fail-closed unit, and a later bad run replaces
# a good one: the last boot's command line always wins.
dir="$tmp/overwrite"
run 'ip=10.42.0.2::10.42.0.1:255.255.0.0:::off:1.1.1.1' "$dir"
assert_static "$dir" "overwrite/valid" "10.42.0.2/16" "10.42.0.1" 1.1.1.1
run 'ip=not-a-network' "$dir"
assert_fail_closed "overwrite/bad" "$dir"
run 'ip=10.42.0.3::10.42.0.1:255.255.0.0:::off:1.1.1.1' "$dir"
assert_static "$dir" "overwrite/valid-again" "10.42.0.3/16" "10.42.0.1" 1.1.1.1

# 5b. A real failure (not malformed input) must fail the unit: the networkd
# drop-in requires it, so networkd is not started and cannot fall back to the
# image's DHCP unit. These cases assert the non-zero status and that no unit
# was installed.
hard_fail() {
	local what=$1 dir=$2
	if [[ -e $dir/$unit_name ]]; then
		rm -f "$dir/$unit_name"
	fi
	if BBRAFT_CMDLINE_FILE="$tmp/hard/cmdline" BBRAFT_NETWORK_DIR="$dir" \
		"$generator" >/dev/null 2>"$tmp/stderr"; then
		fail "$what: generator succeeded; networkd would not be gated"
	else
		pass "$what: generator failed, so networkd is gated"
	fi
	if [[ -e $dir/$unit_name ]]; then
		fail "$what: generator installed a unit despite the failure"
	fi
}
mkdir -p "$tmp/hard"
printf '%s\n' 'ip=10.42.0.2::10.42.0.1:255.255.0.0:::off' >"$tmp/hard/cmdline"

# Unreadable command line.
rm -f "$tmp/hard/cmdline"
mkdir -p "$tmp/hard/missing-cmdline"
hard_fail "missing-cmdline" "$tmp/hard/missing-cmdline"
printf '%s\n' 'ip=10.42.0.2::10.42.0.1:255.255.0.0:::off' >"$tmp/hard/cmdline"

# Output directory cannot be created.
: >"$tmp/hard/not-a-dir"
hard_fail "not-a-directory" "$tmp/hard/not-a-dir"

# Output directory is not writable. Root bypasses mode bits, so only assert it
# for a normal user (the images check runs unprivileged; the KVM run may not).
if [ "$(id -u)" -eq 0 ]; then
	printf 'SKIP read-only-directory check: running as root\n'
else
	mkdir -p "$tmp/hard/readonly"
	chmod 0500 "$tmp/hard/readonly"
	hard_fail "read-only-directory" "$tmp/hard/readonly"
	chmod 0700 "$tmp/hard/readonly"
fi

# 5c. A directory at the exact unit path must fail the publication, not accept
# a move of the unit inside the directory (mv without -T would exit 0, leaving
# networkd with no unit at the path it reads).
assert_publication_refused() {
	local what=$1 cmdline=$2 dir="$tmp/publish/$1"
	mkdir -p "$dir/$unit_name"
	printf '%s\n' "$cmdline" >"$tmp/cmdline"
	if BBRAFT_CMDLINE_FILE="$tmp/cmdline" BBRAFT_NETWORK_DIR="$dir" \
		"$generator" >/dev/null 2>"$tmp/stderr"; then
		fail "$what: generator succeeded with a directory unit target"
	else
		pass "$what: directory unit target fails"
	fi
	if [ -z "$(find "$dir/$unit_name" -mindepth 1 -maxdepth 1 -print -quit)" ]; then
		pass "$what: nothing was moved inside the directory"
	else
		fail "$what: the temporary unit was moved inside the directory"
	fi
	if compgen -G "$dir/.$unit_name.tmp.*" >/dev/null; then
		fail "$what: temporary unit left behind"
	else
		pass "$what: no temporary unit left behind"
	fi
}
assert_publication_refused "dir-target-valid" 'ip=10.42.0.2::10.42.0.1:255.255.0.0:::off'
assert_publication_refused "dir-target-malformed" 'ip='

# 5d. A failed heredoc write during fail-closed emission must not be followed
# by a successful move of a partial unit. fail_closed runs from an OR list, so
# set -e is suppressed inside it and the script must check the write and the
# move explicitly. The fake cat fails only for the fail-closed heredoc.
fakebin="$tmp/fakebin"
mkdir -p "$fakebin"
marker="$tmp/fake-cat-fired"
cat >"$fakebin/cat" <<'EOS'
#!/bin/sh
if [ "$#" -gt 0 ]; then exec /bin/cat "$@"; fi
tmpf=$(mktemp) || exit 1
/bin/cat >"$tmpf" || { rm -f "$tmpf"; exit 1; }
if grep -q 'after a malformed kernel ip= parameter' "$tmpf"; then
	: >"$BBRAFT_FAKE_CAT_MARKER"
	printf 'partial\n'
	rm -f "$tmpf"
	exit 1
fi
/bin/cat "$tmpf"
rc=$?
rm -f "$tmpf"
exit $rc
EOS
chmod 0755 "$fakebin/cat"
dir="$tmp/fakecat"
mkdir -p "$dir"
printf '%s\n' 'ip=' >"$tmp/cmdline"
if PATH="$fakebin:$PATH" BBRAFT_FAKE_CAT_MARKER="$marker" \
	BBRAFT_CMDLINE_FILE="$tmp/cmdline" BBRAFT_NETWORK_DIR="$dir" \
	"$generator" >/dev/null 2>"$tmp/stderr"; then
	fail "fail-closed heredoc failure: generator exited 0"
else
	pass "fail-closed heredoc failure: generator exits nonzero"
fi
if [ -e "$marker" ]; then
	pass "controlled cat failure fired during fail-closed emission"
else
	fail "controlled cat failure did not fire; the case proved nothing"
fi
if [ -e "$dir/$unit_name" ]; then
	fail "fail-closed heredoc failure published a partial unit"
else
	pass "fail-closed heredoc failure published no unit"
fi
if compgen -G "$dir/.$unit_name.tmp.*" >/dev/null; then
	fail "fail-closed heredoc failure left a partial temporary file"
else
	pass "fail-closed heredoc failure left no temporary file"
fi

# 6. Parser hygiene: kernel data is never evaluated, never run through a shell
# and never read from a key path.
if grep -v '^[[:space:]]*#' "$generator" |
	grep -Eq '\beval\b|(^|[[:space:]])(sh|bash)[[:space:]]+-c'; then
	fail "generator evaluates or shells out kernel data"
else
	pass "generator has no eval or shell -c"
fi
if grep -q 'ssh' "$generator"; then
	fail "generator mentions ssh; it must never read host-key material"
else
	pass "generator ignores SSH key material"
fi

# 7. Image wiring: the unit exists, runs before networkd, is enabled by the
# chroot postinst and is installed by the build.
unit_file="$script_dir/mkosi.extra/usr/lib/systemd/system/$service"
if [[ -f $unit_file ]]; then
	pass "systemd unit $service is present"
else
	fail "systemd unit $service is missing"
fi
if grep -q '^Before=.*systemd-networkd.service' "$unit_file"; then
	pass "$service runs before systemd-networkd"
else
	fail "$service does not order itself before systemd-networkd"
fi
if grep -q "systemctl enable $service" "$script_dir/mkosi.postinst.chroot"; then
	pass "postinst enables $service"
else
	fail "postinst does not enable $service"
fi
if grep -qx 'systemctl mask systemd-network-generator.service' \
	"$script_dir/mkosi.postinst.chroot"; then
	pass "postinst masks the stock generator and does not ignore the failure"
else
	fail "postinst does not deterministically mask the stock generator"
fi
if grep -q 'systemctl mask systemd-network-generator.service.*||' \
	"$script_dir/mkosi.postinst.chroot"; then
	fail "postinst ignores a mask failure; two components could own ip="
fi
dropin="$script_dir/mkosi.extra/etc/systemd/system/systemd-networkd.service.d/10-bbraft-network-config.conf"
if [[ -f $dropin ]] &&
	grep -qx 'Requires=bbraft-network-config.service' "$dropin" &&
	grep -qx 'After=bbraft-network-config.service' "$dropin"; then
	pass "networkd requires the generator, so a real failure gates DHCP fallback"
else
	fail "networkd does not require the generator; a write failure could fall back to DHCP"
fi
if grep -q '10-bbraft-network-config.conf' "$script_dir/build.sh"; then
	pass "build.sh installs the networkd drop-in"
else
	fail "build.sh does not install the networkd drop-in"
fi
if grep -q 'bbraft-network-config' "$script_dir/build.sh"; then
	pass "build.sh installs the generator"
else
	fail "build.sh does not install the generator"
fi
if [[ -f "$script_dir/mkosi.extra/etc/systemd/network/20-bbraft.network" ]]; then
	pass "image DHCP unit still ships for user-mode networking"
else
	fail "image DHCP unit was removed; user-mode networking would break"
fi

if [ "$failures" -ne 0 ]; then
	printf 'net_config_test: %d failure(s)\n' "$failures" >&2
	exit 1
fi
printf 'net_config_test: all checks passed\n'
