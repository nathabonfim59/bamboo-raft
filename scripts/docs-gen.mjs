// Go API reference (gomarkdoc)

function goPackages() {
  const out = execFileSync('go', ['list', '-f', '{{if .GoFiles}}{{.Dir}}{{end}}', './...'], { cwd: root, encoding: 'utf-8' });
  return out.split('\n').filter(Boolean).map((dir) => './' + toPosix(relative(root, dir)));
}

function generateGo() {
  rmSync(goDir, { recursive: true, force: true });
  mkdirSync(goDir, { recursive: true });
  console.log('Generating the Go API reference with gomarkdoc...');
  execFileSync(
    'go',
    [
      'run',
      `github.com/princjef/gomarkdoc/cmd/gomarkdoc@${gomarkdocVersion}`,
      '--repository.url', repositoryUrl,
      '--repository.default-branch', defaultBranch,
      '--repository.path', '/',
      '--output', join(goDir, '{{.Dir}}', 'index.md'),
      ...goPackages(),
    ],
    { cwd: root, stdio: 'inherit' },
  );

  const found = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) walk(path);
      else if (entry.name === 'index.md' && dir !== goDir) found.push({ path, dir: toPosix(relative(goDir, dir)) });
    }
  };
  walk(goDir);
  const pkgs = found.map((p) => ({ ...p, summary: goSummary(p.path), group: goGroup(p.dir) })).sort((a, b) => a.dir.localeCompare(b.dir));

  const groups = ['Commands', 'Wire contracts', 'Packages', 'Image tools'];
  const sections = groups
    .map((name) => {
      const items = pkgs.filter((p) => p.group === name);
      if (!items.length) return '';
      const lines = items.map((p) => `- [\`${p.dir}\`](/api-reference/go/${p.dir}/)${p.summary ? `: ${prose(p.summary)}.` : ''}`);
      return `## ${name}\n\n${lines.join('\n')}`;
    })
    .filter(Boolean)
    .join('\n\n');
  write(
    join(goDir, 'index.md'),
    `${marker}\n\n# Go API reference\n\nThe exported identifiers of every Go package in the module \`github.com/nathabonfim59/bamboo-raft\`, generated from the source comments by [gomarkdoc](https://github.com/princjef/gomarkdoc). Almost all packages live under \`internal/\`, so other Go modules cannot import them. The pages are for people who read or extend bamboo-raft. To drive bamboo-raft from your own code, use the [HTTP API](/api-reference/http/).\n\n${sections}\n`,
  );
  return pkgs;
}

function goGroup(dir) {
  if (dir.startsWith('cmd/')) return 'Commands';
  if (dir.startsWith('internal/proto/')) return 'Wire contracts';
  if (dir.startsWith('images')) return 'Image tools';
  return 'Packages';
}

// The first sentence of the package comment, which gomarkdoc prints right after the import block.
function goSummary(file) {
  const text = readFileSync(file, 'utf-8');
  const after = text.split('```\n\n')[1] ?? '';
  const first = (after.split('\n\n')[0] ?? '').replace(/\\(.)/g, '$1').replace(/\s+/g, ' ').trim();
  if (first.startsWith('#') || first.startsWith('<')) return '';
  const end = first.search(/\.(\s|$)/);
  return end === -1 ? first : first.slice(0, end);
}

// ---------------------------------------------------------------------------------------------

const http = generateHTTP();
const pkgs = generateGo();
if (!pkgs.length) {
  console.error('gomarkdoc produced no packages');
  process.exit(1);
}
write(
  join(apiDir, 'index.md'),
  `${marker}\n\n# API reference\n\n- [HTTP API reference](/api-reference/http/): every \`/api/v1\` and \`/api/bbraft\` operation and schema.\n- [Go API reference](/api-reference/go/): every Go package in the repository.\n- [API behavior](/api): how the operations behave beyond the schemas.\n\nThese pages are generated from the OpenAPI documents and the Go source on every build.\n`,
);
console.log(
  `Wrote ${http.opCount} HTTP operations on ${http.pages.length + 3} pages and ${pkgs.length} Go package pages.`,
);
