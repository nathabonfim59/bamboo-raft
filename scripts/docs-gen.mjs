#!/usr/bin/env node
/**
 * Generates the API reference pages from their sources of truth:
 *
 * - docs/api-reference/http/  from the OpenAPI documents api/bbraft-v1.yaml and api/bbraft-ext.yaml
 * - docs/api-reference/go/    from the Go source, with gomarkdoc
 *
 * The output is gitignored: `npm run docs:build` (and CI) regenerate it before every build, so it can
 * never drift from the spec or the code. Hand-written pages are the repository's Markdown, read in
 * place; see scripts/doc-links.mjs.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseYAML } from 'yaml';
import { defaultBranch, repositoryUrl } from './doc-links.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const apiDir = join(root, 'docs', 'api-reference');
const httpDir = join(apiDir, 'http');
const goDir = join(apiDir, 'go');

const gomarkdocVersion = 'v1.1.0';
// Generated pages have no source Markdown to edit, so they hide the edit link.
const marker = '---\neditLink: false\n---\n\n<!-- Generated by npm run docs:api from the OpenAPI documents and the Go source. -->';

const toPosix = (p) => p.split('\\').join('/');
const write = (path, text) => {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text.replace(/\n{3,}/g, '\n\n').trimEnd() + '\n');
};

// ---------------------------------------------------------------------------------------------
// Markdown helpers

/** Escapes text for VitePress (Vue templates) outside code spans. */
function prose(text) {
  return String(text ?? '')
    .split(/(`[^`]*`)/)
    .map((part, i) => (i % 2 ? part : part.replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\{\{/g, '&#123;&#123;')))
    .join('')
    .trim();
}

/** One table cell: a single line with escaped pipes. */
const cell = (text) => prose(text).replace(/\s*\n\s*/g, ' ').replace(/\|/g, '\\|');

const table = (head, rows) =>
  rows.length
    ? [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n')
    : '';

// ---------------------------------------------------------------------------------------------
// HTTP API reference

const tagSlug = (tag) => tag.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

/** One OpenAPI document plus the rules for linking its schemas. */
class Spec {
  constructor(file, { anchorPrefix, page }) {
    this.file = file;
    this.doc = parseYAML(readFileSync(join(root, file), 'utf-8'));
    this.anchorPrefix = anchorPrefix;
    this.page = page; // page that holds this document's schemas
    this.base = this.doc.servers?.[0]?.url ?? '';
  }

  ref(ref) {
    const parts = ref.replace(/^#\//, '').split('/');
    let node = this.doc;
    for (const p of parts) node = node?.[p.replace(/~1/g, '/').replace(/~0/g, '~')];
    if (node === undefined) throw new Error(`${this.file}: unresolved $ref ${ref}`);
    return node;
  }

  deref(node) {
    const seen = new Set();
    while (node && node.$ref) {
      if (seen.has(node.$ref)) throw new Error(`${this.file}: $ref cycle at ${node.$ref}`);
      seen.add(node.$ref);
      node = this.ref(node.$ref);
    }
    return node;
  }

  schemaAnchor(name) {
    return this.anchorPrefix + name;
  }

  schemaLink(name, fromPage) {
    const href = fromPage === this.page ? `#${this.schemaAnchor(name)}` : `/api-reference/http/${this.page}#${this.schemaAnchor(name)}`;
    return `[${name}](${href})`;
  }

  /** Short type expression for a schema, with links to named schemas. */
  type(schema, fromPage) {
    if (!schema) return 'any';
    if (schema.$ref) {
      const name = schema.$ref.split('/').pop();
      return schema.$ref.startsWith('#/components/schemas/') ? this.schemaLink(name, fromPage) : name;
    }
    if (schema.const !== undefined) return `\`${JSON.stringify(schema.const)}\``;
    for (const key of ['oneOf', 'anyOf']) if (schema[key]) return schema[key].map((s) => this.type(s, fromPage)).join(' or ');
    if (schema.allOf) return schema.allOf.map((s) => this.type(s, fromPage)).join(' and ');
    if (Array.isArray(schema.type)) return schema.type.map((t) => this.type({ ...schema, type: t }, fromPage)).join(' or ');
    switch (schema.type) {
      case 'array':
        return `${this.type(schema.items, fromPage)}[]`;
      case 'object':
        if (schema.additionalProperties && typeof schema.additionalProperties === 'object' && !schema.properties) {
          return `map of ${this.type(schema.additionalProperties, fromPage)}`;
        }
        return 'object';
      case undefined:
        return schema.properties ? 'object' : 'any';
      default:
        return schema.format ? `${schema.type} (${schema.format})` : schema.type;
    }
  }

  /** Extra facts for the description column: enum values, default, bounds. */
  facts(schema) {
    const out = [];
    const s = this.deref(schema) ?? {};
    const enumValues = s.enum ?? (s.oneOf ?? s.anyOf ?? []).flatMap((x) => this.deref(x)?.enum ?? []);
    if (enumValues.length) out.push(`One of ${enumValues.map((v) => `\`${JSON.stringify(v)}\``).join(', ')}.`);
    if (schema.default !== undefined) out.push(`Default \`${JSON.stringify(schema.default)}\`.`);
    const bounds = [];
    if (s.minimum !== undefined) bounds.push(`min ${s.minimum}`);
    if (s.maximum !== undefined) bounds.push(`max ${s.maximum}`);
    if (s.minLength !== undefined) bounds.push(`min length ${s.minLength}`);
    if (s.maxLength !== undefined) bounds.push(`max length ${s.maxLength}`);
    if (s.pattern) bounds.push(`pattern \`${s.pattern}\``);
    if (bounds.length) { const b = bounds.join(', '); out.push(b[0].toUpperCase() + b.slice(1) + '.'); }
    return out.join(' ');
  }

  /** Field rows of an object schema; inline nested objects get dotted names. */
  fieldRows(schema, fromPage, prefix = '', depth = 0) {
    const s = schema.$ref ? null : schema;
    if (!s) return [];
    const merged = { properties: {}, required: [] };
    for (const part of [s, ...(s.allOf ?? []).map((x) => this.deref(x))]) {
      Object.assign(merged.properties, part.properties ?? {});
      merged.required.push(...(part.required ?? []));
    }
    const rows = [];
    for (const [name, prop] of Object.entries(merged.properties)) {
      const full = prefix + name;
      const desc = [prop.description, this.facts(prop)].filter(Boolean).join(' ');
      rows.push([`\`${full}\``, cell(this.type(prop, fromPage)), merged.required.includes(name) ? 'yes' : '', cell(desc)]);
      if (depth < 3 && !prop.$ref) {
        if (prop.type === 'object' && prop.properties) rows.push(...this.fieldRows(prop, fromPage, `${full}.`, depth + 1));
        if (prop.type === 'array' && prop.items && !prop.items.$ref && prop.items.properties) {
          rows.push(...this.fieldRows(prop.items, fromPage, `${full}[].`, depth + 1));
        }
      }
    }
    return rows;
  }

  fieldsTable(schema, fromPage) {
    return table(['Field', 'Type', 'Required', 'Description'], this.fieldRows(schema, fromPage));
  }

  operations() {
    const ops = [];
    for (const [path, item] of Object.entries(this.doc.paths ?? {})) {
      for (const method of ['get', 'put', 'post', 'patch', 'delete']) {
        const op = item[method];
        if (!op) continue;
        const params = [...(item.parameters ?? []), ...(op.parameters ?? [])].map((p) => this.deref(p));
        ops.push({ path, method: method.toUpperCase(), op, params, tag: op.tags?.[0] ?? 'Other' });
      }
    }
    return ops;
  }

  renderOperation({ path, method, op, params }, fromPage) {
    const out = [];
    out.push(`## ${prose(op.summary ?? op.operationId)} {#${op.operationId}}`);
    out.push(`\`\`\`http\n${method} ${this.base}${path}\n\`\`\``);
    out.push(`Operation \`${op.operationId}\`${op.security && op.security.length === 0 ? '. No bearer authentication; the token in the URL is the credential.' : '.'}`);
    if (op.description) out.push(prose(op.description));

    if (params.length) {
      out.push('### Parameters');
      out.push(
        table(
          ['Name', 'In', 'Type', 'Required', 'Description'],
          params.map((p) => [
            `\`${p.name}\``,
            p.in,
            cell(this.type(p.schema, fromPage)),
            p.required ? 'yes' : '',
            cell([p.description, p.schema ? this.facts(p.schema) : ''].filter(Boolean).join(' ')),
          ]),
        ),
      );
    }

    const body = op.requestBody && this.deref(op.requestBody);
    if (body) {
      out.push('### Request body');
      for (const [media, content] of Object.entries(body.content ?? {})) {
        const schema = content.schema;
        const line = [`\`${media}\``, schema ? this.type(schema, fromPage) : '', body.required ? '(required)' : '(optional)'];
        out.push(line.filter(Boolean).join(' '));
        if (body.description) out.push(prose(body.description));
        const resolved = schema && this.deref(schema);
        if (resolved && (resolved.properties || resolved.allOf)) out.push(this.fieldsTable(resolved, fromPage));
      }
    }

    out.push('### Responses');
    const rows = Object.entries(op.responses ?? {}).map(([status, response]) => {
      const r = this.deref(response);
      const bodies = Object.entries(r.content ?? {}).map(
        ([media, c]) => `\`${media}\`${c.schema ? ' ' + this.type(c.schema, fromPage) : ''}`,
      );
      return [`\`${status}\``, cell(r.description ?? ''), cell(bodies.join(', '))];
    });
    out.push(table(['Status', 'Description', 'Body'], rows));
    return out.join('\n\n');
  }

  renderSchemas(fromPage, heading) {
    const out = [];
    const schemas = this.doc.components?.schemas ?? {};
    for (const name of Object.keys(schemas).sort()) {
      const s = schemas[name];
      out.push(`${heading} ${name} {#${this.schemaAnchor(name)}}`);
      if (s.description) out.push(prose(s.description));
      const kind = this.type(s, fromPage);
      const fields = s.properties || s.allOf ? this.fieldsTable(s, fromPage) : '';
      if (fields) out.push(fields);
      else {
        out.push(`Type: ${kind}.`);
        const facts = this.facts(s);
        if (facts) out.push(prose(facts));
      }
    }
    return out.join('\n\n');
  }
}

function generateHTTP() {
  rmSync(httpDir, { recursive: true, force: true });
  const v1 = new Spec('api/bbraft-v1.yaml', { anchorPrefix: '', page: 'schemas' });
  const ext = new Spec('api/bbraft-ext.yaml', { anchorPrefix: 'ext-', page: 'extensions' });
  const source = (file) => `[\`${file}\`](${repositoryUrl}/blob/${defaultBranch}/${file})`;

  const v1Ops = v1.operations();
  const tags = (v1.doc.tags ?? []).map((t) => t.name);
  for (const op of v1Ops) if (!tags.includes(op.tag)) tags.push(op.tag);

  const pages = [];
  for (const tag of tags) {
    const ops = v1Ops.filter((o) => o.tag === tag);
    if (!ops.length) continue;
    const slug = tagSlug(tag);
    const description = v1.doc.tags?.find((t) => t.name === tag)?.description;
    pages.push({ tag, slug, ops, description });
    write(
      join(httpDir, `${slug}.md`),
      [
        marker,
        `# ${tag} {#page-${slug}}`,
        description ? prose(description) : '',
        `Generated from ${source(v1.file)}. Schemas are on the [schemas page](/api-reference/http/schemas).`,
        ...ops.map((o) => v1.renderOperation(o, slug)),
      ].join('\n\n'),
    );
  }

  write(
    join(httpDir, 'schemas.md'),
    [marker, '# Schemas', `Every schema of ${source(v1.file)}, the \`/api/v1\` document.`, v1.renderSchemas('schemas', '##')].join('\n\n'),
  );

  write(
    join(httpDir, 'extensions.md'),
    [
      marker,
      '# Extensions',
      prose(ext.doc.info?.description ?? ''),
      `Generated from ${source(ext.file)}.`,
      ...ext.operations().map((o) => ext.renderOperation(o, 'extensions')),
      '## Extension schemas',
      ext.renderSchemas('extensions', '###'),
    ].join('\n\n'),
  );

  const opRows = (spec, ops, page) =>
    ops.map(({ path, method, op }) => [
      `[${cell(op.summary ?? op.operationId)}](/api-reference/http/${page(op)}#${op.operationId})`,
      `\`${method} ${spec.base}${path}\``,
    ]);
  const overview = [
    marker,
    '# HTTP API reference',
    `bamboo-raft serves its sandbox API under \`/api/v1\` and a few server extensions under \`/api/bbraft\`. These pages are generated from the OpenAPI documents ${source(v1.file)} and ${source(ext.file)}; [API behavior](/api) describes what the schemas cannot.`,
    '## Authentication',
    'Every `/api/v1` and `/api/bbraft` call takes the installation API key as a bearer token: `Authorization: Bearer <key>`. The signed upload and download receivers are the exception: their URL token is the only credential.',
    '## Envelopes and errors',
    'Successful responses are JSON objects with `ok: true` and a `type` naming the shape. Errors share one envelope:',
    '```json\n{\n  "ok": false,\n  "type": "sandbox.error",\n  "status": 404,\n  "code": "not_found",\n  "message": "Sandbox not found",\n  "error": {"code": "not_found", "message": "Sandbox not found", "status": 404},\n  "requestId": "req_..."\n}\n```',
    'See [ErrorEnvelope](/api-reference/http/schemas#ErrorEnvelope) and [Error codes by status](/api#error-codes-by-status).',
    '## Operations',
    ...pages.flatMap((p) => [`### ${p.tag}`, table(['Operation', 'Request'], opRows(v1, p.ops, () => p.slug))]),
    '### Extensions',
    table(['Operation', 'Request'], opRows(ext, ext.operations(), () => 'extensions')),
  ];
  write(join(httpDir, 'index.md'), overview.join('\n\n'));
  return { pages, opCount: v1Ops.length + ext.operations().length };
}

